func TestGeneratorWritesColumns(t *testing.T) {
	tmp := t.TempDir()
	writeGeneratorFixture(t, tmp)

	if err := run(config{Root: tmp, OutputPath: filepath.Join(tmp, "pkg", "model"), StructPath: tmp}); err != nil {
		t.Fatalf("run default generator: %v", err)
	}

	if _, err := os.Stat(filepath.Join(tmp, "pkg", "model", "col", "foo.col.go")); !os.IsNotExist(err) {
		t.Fatalf("expected no per-struct file, got err = %v", err)
	}

	allContent, err := os.ReadFile(filepath.Join(tmp, "pkg", "model", "col", "col.go"))
	if err != nil {
		t.Fatalf("read all columns file: %v", err)
	}
	allStr := string(allContent)
	allSnippets := []string{
		"// Code generated by gen-columns DO NOT EDIT.",
		"// WARNING: Changes to this file may cause incorrect behavior",
		"// and will be lost if the code is regenerated",
		"// Generator:",
		"// gen-columns",
		"package col",
		"const (",
		"All  = \"*\"",
		"Id   = \"id\"",
		"Name = \"name\"",
	}
	for _, snippet := range allSnippets {
		if !strings.Contains(allStr, snippet) {
			t.Fatalf("all columns file missing snippet %q\ncontent:\n%s", snippet, allStr)
		}
	}

	idxAll := strings.Index(allStr, "All  = \"*\"")
	idxId := strings.Index(allStr, "Id   = \"id\"")
	if idxAll == -1 || idxId == -1 {
		t.Fatalf("expected All and Id constants in generated content:\n%s", allStr)
	}
	if idxAll > idxId {
		t.Fatalf("expected All constant to appear before Id\ncontent:\n%s", allStr)
	}
}

