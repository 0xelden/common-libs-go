func TestRunCommandHelp(t *testing.T) {
	for _, arg := range []string{"-h", "--help"} {
		t.Run(arg, func(t *testing.T) {
			var stdout bytes.Buffer
			var stderr bytes.Buffer

			code := runCommand([]string{arg}, &stdout, &stderr)
			if code != 0 {
				t.Fatalf("expected exit code 0, got %d", code)
			}
			if stderr.Len() != 0 {
				t.Fatalf("expected empty stderr, got %q", stderr.String())
			}

			out := stdout.String()
			for _, snippet := range []string{
				"Usage of gen-columns:",
				"-full",
				"-output-path string",
				"-struct-path string",
			} {
				if !strings.Contains(out, snippet) {
					t.Fatalf("help output missing snippet %q\noutput:\n%s", snippet, out)
				}
			}
		})
	}
}

func TestLoadConfigDefaultsPaths(t *testing.T) {
	tmp := t.TempDir()
	tmp, err := filepath.EvalSymlinks(tmp)
	if err != nil {
		t.Fatalf("eval symlinks tmp: %v", err)
	}
	prev, err := os.Getwd()
	if err != nil {
		t.Fatalf("getwd: %v", err)
	}
	if err := os.Chdir(tmp); err != nil {
		t.Fatalf("chdir tmp: %v", err)
	}
	defer func() {
		if err := os.Chdir(prev); err != nil {
			t.Fatalf("restore cwd: %v", err)
		}
	}()

	cfg, err := loadConfig(nil)
	if err != nil {
		t.Fatalf("load config: %v", err)
	}
	if cfg.Root != tmp {
		t.Fatalf("expected root %q, got %q", tmp, cfg.Root)
	}
	wantOutput := filepath.Join(tmp, "pkg", "model")
	if cfg.OutputPath != wantOutput {
		t.Fatalf("expected output path %q, got %q", wantOutput, cfg.OutputPath)
	}
	wantStruct := tmp
	if cfg.StructPath != wantStruct {
		t.Fatalf("expected struct path %q, got %q", wantStruct, cfg.StructPath)
	}
	if cfg.Generator != "gen-columns" {
		t.Fatalf("expected generator %q, got %q", "gen-columns", cfg.Generator)
	}
}

