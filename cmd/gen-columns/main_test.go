func TestWarnIdentifierCollisions(t *testing.T) {
	t.Run("writes warning when identifiers collide", func(t *testing.T) {
		origStderr := os.Stderr
		r, w, err := os.Pipe()
		if err != nil {
			t.Fatalf("pipe: %v", err)
		}
		os.Stderr = w
		defer func() {
			os.Stderr = origStderr
		}()

		columns := []string{"foo_bar", "foo-bar", "id"}
		warnIdentifierCollisions(columns)

		if err := w.Close(); err != nil {
			t.Fatalf("close writer: %v", err)
		}

		out, err := io.ReadAll(r)
		if err != nil {
			t.Fatalf("read stderr: %v", err)
		}

		got := string(out)
		want := "warning: pkg/model/col/col.go constant FooBar has multiple column values: foo-bar, foo_bar\n"
		if got != want {
			t.Fatalf("unexpected warning\nwant: %q\ngot:  %q", want, got)
		}
	})

	t.Run("no warning when identifiers unique", func(t *testing.T) {
		origStderr := os.Stderr
		r, w, err := os.Pipe()
		if err != nil {
			t.Fatalf("pipe: %v", err)
		}
		os.Stderr = w
		defer func() {
			os.Stderr = origStderr
		}()

		columns := []string{"foo_bar", "bar_baz"}
		warnIdentifierCollisions(columns)

		if err := w.Close(); err != nil {
			t.Fatalf("close writer: %v", err)
		}

		out, err := io.ReadAll(r)
		if err != nil {
			t.Fatalf("read stderr: %v", err)
		}
		if len(out) != 0 {
			t.Fatalf("expected no warnings, got %q", string(out))
		}
	})
}
