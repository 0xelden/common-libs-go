const identityDDL = `
create table public.sample_table (
    id bigint generated always as identity primary key,
    name varchar(50),
    year integer generated always as (2024) stored
);
`

func TestParseCreateTableIdentityColumn(t *testing.T) {
	table, err := ParseCreateTable(identityDDL)
	if err != nil {
		t.Fatalf("ParseCreateTable returned error: %v", err)
	}
	cols := map[string]Column{}
	for _, col := range table.Columns {
		cols[col.Name] = col
	}
	if id := cols["id"]; id.IsGenerated || !id.IsIdentity || id.GenerationExpression != "" {
		t.Fatalf("identity id should not be generated: %+v", id)
	}
	if year := cols["year"]; !year.IsGenerated || year.IsIdentity {
		t.Fatalf("stored expression column should be generated: %+v", year)
	}
}

func TestParseCreateTableIdentityByDefaultWithOptions(t *testing.T) {
	table, err := ParseCreateTable(`
create table public.sample_table (
    id integer generated by default as identity (start with 10) primary key
);
`)
	if err != nil {
		t.Fatalf("ParseCreateTable returned error: %v", err)
	}
	id := table.Columns[0]
	if id.IsGenerated || !id.IsIdentity || id.GenerationExpression != "" {
		t.Fatalf("identity id should not be generated: %+v", id)
	}
}

func TestIdentityColumnMatchesBetweenDDLAndDatabase(t *testing.T) {
	db := newStubDB(
		[][]driver.Value{{"id"}},
		[][]driver.Value{
			{"id", "bigint", "int8", true, false, false, "", true},
			{"name", "character varying", "varchar", false, false, false, "", false},
			{"year", "integer", "int4", false, false, true, "2024", false},
		},
	)
	defer func() {
		currentStubData = nil
		_ = db.Close()
	}()

	fromDB, err := loadTableDefinition(db, "public.sample_table")
	if err != nil {
		t.Fatalf("loadTableDefinition returned error: %v", err)
	}
	fromDDL, err := ParseCreateTable(identityDDL)
	if err != nil {
		t.Fatalf("ParseCreateTable returned error: %v", err)
	}
	for i := range fromDDL.Columns {
		a, b := fromDDL.Columns[i], fromDB.Columns[i]
		if a.Name != b.Name || a.IsGenerated != b.IsGenerated || a.IsIdentity != b.IsIdentity {
			t.Fatalf("column %d differs between DDL and database:\nddl: %+v\ndb:  %+v", i, a, b)
		}
	}
}

func TestGenerateFilesIdentityId(t *testing.T) {
	table, err := ParseCreateTable(identityDDL)
	if err != nil {
		t.Fatalf("ParseCreateTable returned error: %v", err)
	}
	files, err := generateFiles(table, "gitlab.com/example/project", nil, true)
	if err != nil {
		t.Fatalf("generateFiles returned error: %v", err)
	}
	paths := map[string]string{}
	for _, file := range files {
		paths[file.Path] = file.Content
	}

	modelFile := paths[filepath.Join("modules", "sample_table", "model", "sample_table_model.go")]
	dtoStart := strings.Index(modelFile, "type SampleTableDto struct")
	dtoEnd := strings.Index(modelFile[dtoStart:], "}")
	dtoBody := modelFile[dtoStart : dtoStart+dtoEnd]
	if !strings.Contains(dtoBody, "Id int64") {
		t.Fatalf("dto should keep identity id:\n%s", modelFile)
	}
	if !strings.Contains(dtoBody, `validate:"required|int"`) {
		t.Fatalf("identity id should be validated as int:\n%s", modelFile)
	}
	if strings.Contains(modelFile, "required|uuid") {
		t.Fatalf("identity id should not be validated as uuid:\n%s", modelFile)
	}

	if !strings.Contains(modelFile, "Id int64 `form:\"id\" json:\"id\" validate:\"required|int\"`") {
		t.Fatalf("edit form should include identity id:\n%s", modelFile)
	}

	ctrlFile := paths[filepath.Join("modules", "sample_table", "sample_table.ctrl.go")]
	if !strings.Contains(ctrlFile, "return helper.ToString(res.Id), nil") {
		t.Fatalf("create should convert numeric id to string:\n%s", ctrlFile)
	}
}

func TestGenerateFilesUUIDIdKeepsUUIDRule(t *testing.T) {
	table := &Table{
		Name: "sample_table",
		Columns: []Column{
			{Name: "id", RawType: "uuid", NotNull: true, IsPrimary: true},
			{Name: "name", RawType: "varchar(50)"},
		},
	}
	files, err := generateFiles(table, "gitlab.com/example/project", nil, true)
	if err != nil {
		t.Fatalf("generateFiles returned error: %v", err)
	}
	for _, file := range files {
		if strings.HasSuffix(file.Path, "_model.go") && !strings.Contains(file.Content, `validate:"required|uuid"`) {
			t.Fatalf("uuid id should keep uuid rule:\n%s", file.Content)
		}
		if strings.HasSuffix(file.Path, ".ctrl.go") && !strings.Contains(file.Content, "return res.Id, nil") {
			t.Fatalf("uuid id should be returned as is:\n%s", file.Content)
		}
	}
}
